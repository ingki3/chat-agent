/**
 * Every text column of the schema, and how known secrets are kept out of it (review round 26). A column holding
 * user-supplied or runtime text is scrubbed on every write (`write`: where) and again by the background rescrub
 * when a secret is registered (`rescrub`: how its value is read); anything else is exempt, with the reason.
 * `test/known-secrets.test.ts` checks that this list names every text column the migrations create — a new column
 * cannot be added without deciding.
 *
 * Rescrub kinds: `text` a plain string; `deep` JSON, value by value; `parts` a message's parts (text parts as one
 * text); `content` an artifact version's content (canonical JSON for chart/table/document, else text).
 */
